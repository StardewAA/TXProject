CREATE TABLE IF NOT EXISTS infra_work_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id BIGINT NOT NULL, user_id BIGINT NOT NULL, user_name VARCHAR(128),
 module VARCHAR(64), action VARCHAR(32), business_key VARCHAR(1000), summary VARCHAR(512),
 request_params CLOB, changes CLOB, result_code INT, result_msg VARCHAR(1024),
 user_ip VARCHAR(64), user_agent VARCHAR(1024), begin_time TIMESTAMP, duration INT,
 trace_id VARCHAR(128), request_url VARCHAR(1024), request_method VARCHAR(16),
 creator VARCHAR(64) DEFAULT '', updater VARCHAR(64) DEFAULT '',
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 deleted BOOLEAN DEFAULT FALSE
);
DELETE FROM infra_work_log;
