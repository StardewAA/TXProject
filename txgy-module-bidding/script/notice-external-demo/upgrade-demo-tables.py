def main():
    with open(SAMPLES, encoding='utf-8') as f:
        samples = json.load(f)
    builders = {'1900000001002': html_1002, '1900000001003': html_1003,
                '1900000001004': html_1004}
    for item in samples:
        rid = str(item['id'])
        if rid in builders:
            item['contentHtml'] = builders[rid](item['title'])
    with open(SAMPLES, 'w', encoding='utf-8') as f:
        json.dump(samples, f, ensure_ascii=False, indent=2)
    for item in samples:
        rid = str(item['id'])
        html = item['contentHtml']
        print(rid, 'len', len(html), 'table', html.count('<table>'),
              'tr', html.count('<tr>'), '保留段落', html.count('<p>'))
    # 冒烟：确认仍能被"去标签取文本"还原出关键信息（不丢正文）
    for rid in ('1900000001002', '1900000001003', '1900000001004'):
        item = next(x for x in samples if str(x['id']) == rid)
        import re
        text = re.sub(r'<[^>]+>', '', item['contentHtml'])
        keys = ('陕西化建工程', '陕西德源招标', '公示') if rid == '1900000001002' \
            else ('河南省宇祯', '国信国际工程咨询', '公示')
        for key in keys:
            assert key in text, (rid, key)
    print('OK: 关键信息在去标签文本中可还原')


if __name__ == '__main__':
    main()
