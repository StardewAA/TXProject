def p(text):
    return '<p>' + text + '</p>'


def h(level, text):
    return f'<h{level}>{text}</h{level}>'


def table(headers, rows):
    thead = ''.join('<th>' + c + '</th>' for c in headers)
    body = ''
    for row in rows:
        body += '<tr>' + ''.join('<td>' + str(c) + '</td>' for c in row) + '</tr>'
    return ('<table><thead><tr>' + thead + '</tr></thead><tbody>' + body
            + '</tbody></table>')


