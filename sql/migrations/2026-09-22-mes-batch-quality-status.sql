-- ============================================================================
-- R3: 批次质量状态（仅 IPQC 生产批次）
--
-- mes_wm_batch.quality_status 字段已存在，但存量数据全部为 NULL（孤儿字段）。
-- 本脚本将存量空值回填为 0（待检验），与 R3 运行时逻辑保持一致：
--   - 生产入库生成批次时默认 0（待检验）
--   - IPQC 完成后回写批次质量状态（1=合格 / 2=不合格）
--
-- 说明：本脚本为幂等脚本（UPDATE 只影响 quality_status IS NULL 的行，可重复执行）。
-- ============================================================================

UPDATE `mes_wm_batch`
SET `quality_status` = 0
WHERE `quality_status` IS NULL;
