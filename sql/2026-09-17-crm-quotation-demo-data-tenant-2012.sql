SELECT '=== 报价单（含明细金额核对） ===' AS section;
SELECT q.id, q.no, q.name, q.audit_status AS 状态, q.contract_id AS 合同,
       q.total_price AS 报价总额,
       (SELECT IFNULL(SUM(p.total_price), 0) FROM `crm_quotation_product` p WHERE p.quotation_id = q.id) AS 明细合计,
       (SELECT COUNT(*) FROM `crm_quotation_product` p WHERE p.quotation_id = q.id) AS 明细条数,
       c.name AS 客户, b.name AS 商机, q.tenant_id
FROM `crm_quotation` q
LEFT JOIN `crm_customer` c ON c.id = q.customer_id
LEFT JOIN `crm_business` b ON b.id = q.business_id
WHERE q.id BETWEEN 5501 AND 5506
ORDER BY q.id;

SELECT '=== 明细 ===' AS section;
SELECT p.quotation_id, p.product_id, pr.name AS 产品, pr.price AS 产品档案单价,
       p.product_price, p.quotation_price, p.count, p.total_price
FROM `crm_quotation_product` p
LEFT JOIN `crm_product` pr ON pr.id = p.product_id
WHERE p.quotation_id BETWEEN 5501 AND 5506
ORDER BY p.quotation_id, p.product_id;
