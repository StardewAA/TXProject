-- M3/M4：专家咨询业务数据。跨模块支付/IM 接口由整合小组实现。
CREATE TABLE IF NOT EXISTS cms_expert_profile (
  id bigint NOT NULL AUTO_INCREMENT,
  tenant_id bigint NOT NULL,
  user_id bigint NOT NULL COMMENT 'BASE/System 用户编号',
  expert_name varchar(64) NOT NULL,
  professional_title varchar(64) NULL,
  company varchar(128) NULL,
  service_fields varchar(1000) NOT NULL,
  introduction text NULL,
  fixed_price int NOT NULL COMMENT '固定文字咨询价格，分',
  audit_status tinyint NOT NULL DEFAULT 0 COMMENT '0待审核 1通过 2驳回',
  audit_remark varchar(500) NULL,
  enabled bit(1) NOT NULL DEFAULT b'0',
  rating decimal(3,2) NOT NULL DEFAULT 0,
  order_count int NOT NULL DEFAULT 0,
  creator varchar(64) NOT NULL DEFAULT '', create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updater varchar(64) NOT NULL DEFAULT '', update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted bit(1) NOT NULL DEFAULT b'0', version int NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uk_cms_expert_user (tenant_id,user_id,deleted),
  KEY idx_cms_expert_audit (tenant_id,audit_status,enabled)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='CMS专家资料';

CREATE TABLE IF NOT EXISTS consult_order (
  id bigint NOT NULL AUTO_INCREMENT,
  tenant_id bigint NOT NULL COMMENT '专家所属租户',
  customer_tenant_id bigint NOT NULL COMMENT '咨询人所属租户',
  order_no varchar(64) NOT NULL,
  user_id bigint NOT NULL,
  expert_id bigint NOT NULL,
  service_subject varchar(128) NOT NULL,
  question text NOT NULL,
  price int NOT NULL COMMENT '订单金额，分',
  status tinyint NOT NULL COMMENT '0待支付 1待接单 2已接单 3咨询中 4待确认 5已完成 6已取消 7已过期 8已拒单 9退款中 10已退款 11纠纷中',
  pay_order_id bigint NULL COMMENT '由支付整合接口回填',
  im_group_id bigint NULL COMMENT '由IM整合接口回填',
  expire_time datetime NOT NULL,
  paid_time datetime NULL,
  completed_time datetime NULL,
  cancel_reason varchar(500) NULL,
  creator varchar(64) NOT NULL DEFAULT '', create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updater varchar(64) NOT NULL DEFAULT '', update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted bit(1) NOT NULL DEFAULT b'0', version int NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uk_consult_order_no (tenant_id,order_no),
  KEY idx_consult_user (tenant_id,user_id,status),
  KEY idx_consult_customer (customer_tenant_id,user_id,status),
  KEY idx_consult_expert (tenant_id,expert_id,status),
  KEY idx_consult_expire (tenant_id,status,expire_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='专家咨询订单';

CREATE TABLE IF NOT EXISTS consult_evaluation (
  id bigint NOT NULL AUTO_INCREMENT,
  tenant_id bigint NOT NULL,
  order_id bigint NOT NULL,
  user_id bigint NOT NULL,
  expert_id bigint NOT NULL,
  rating tinyint NOT NULL COMMENT '1-5星',
  content varchar(1000) NULL,
  create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted bit(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  UNIQUE KEY uk_consult_evaluation (tenant_id,order_id,deleted),
  KEY idx_consult_evaluation_expert (tenant_id,expert_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='专家咨询评价';

CREATE TABLE IF NOT EXISTS expert_settlement (
  id bigint NOT NULL AUTO_INCREMENT,
  tenant_id bigint NOT NULL,
  order_id bigint NOT NULL,
  expert_id bigint NOT NULL,
  order_amount int NOT NULL,
  commission_rate decimal(5,2) NOT NULL,
  commission_amount int NOT NULL,
  settlement_amount int NOT NULL,
  status tinyint NOT NULL DEFAULT 0 COMMENT '0待结算 1已结算 2驳回',
  proof_url varchar(500) NULL,
  proof_no varchar(128) NULL,
  settled_by bigint NULL,
  settled_time datetime NULL,
  remark varchar(500) NULL,
  creator varchar(64) NOT NULL DEFAULT '', create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updater varchar(64) NOT NULL DEFAULT '', update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted bit(1) NOT NULL DEFAULT b'0', version int NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uk_expert_settlement_order (tenant_id,order_id,deleted),
  KEY idx_expert_settlement_status (tenant_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='专家线下结算凭证';
